if HAS_CIRQ:

    class SiliconExchangeGate(cirq.Gate):
        """Two-qubit gate wrapping a synthesised exchange-pulse unitary."""

        def __init__(self, unitary: np.ndarray, name: str = "SiExchange"):
            super().__init__()
            unitary = np.asarray(unitary)
            if unitary.shape != (4, 4):
                raise ValueError(f"Expected 4x4 unitary matrix, got {unitary.shape}")
            self._unitary_matrix = np.array(unitary, dtype=np.complex128)
            self._name = name

        def _num_qubits_(self) -> int:
            return 2

        def _unitary_(self) -> np.ndarray:
            return self._unitary_matrix

        def _circuit_diagram_info_(self, args) -> "cirq.CircuitDiagramInfo":
            return cirq.CircuitDiagramInfo(wire_symbols=(f"[{self._name}]", f"[{self._name}]"))

        def __repr__(self) -> str:
            return f"SiliconExchangeGate(name='{self._name}')"

else:  # pragma: no cover

    class SiliconExchangeGate:  # type: ignore[no-redef]
        def __init__(self, *args, **kwargs):
            raise RuntimeError("Cirq is not installed.")


class CirqSiliconSimulator:
    """
    Appends T1 / T2* channels after every moment: generalized amplitude damping
    towards the thermal state (|1⟩ = |↓⟩ is the ground state, as in the Lindblad
    model) and phase damping.
    """

    def __init__(self, noise_model: Optional[SiliconNoiseModel] = None):
        self.noise = noise_model or SiliconNoiseModel()

    def damping_parameters(self, gate_duration_ns: float) -> Tuple[float, float]:
        """(γ_amp, γ_phase) for one moment of duration ``gate_duration_ns``."""
        rates = self.noise.lindblad_rates_per_ns()
        t = float(gate_duration_ns)
        gamma_amp = 1.0 - np.exp(-rates["gamma_1"] * t)
        # phase_damp(γ) multiplies coherences by sqrt(1-γ): exp(-γφ t) ⇒ γ = 1 - exp(-2 γφ t)
        gamma_phase = 1.0 - np.exp(-2.0 * rates["gamma_phi"] * t)
        return float(gamma_amp), float(gamma_phase)

    def create_noisy_circuit(self, circuit: "cirq.Circuit", gate_duration_ns: float = 40.0) -> "cirq.Circuit":
        if not HAS_CIRQ:
            raise RuntimeError("Cirq is not installed.")
        g_amp, g_phi = self.damping_parameters(gate_duration_ns)
        p_up = self.noise.excited_state_population()
        noisy = cirq.Circuit()
        for moment in circuit:
            noisy.append(moment)
            for q in moment.qubits:
                if g_amp > 0:
                    noisy.append(cirq.generalized_amplitude_damp(p_up, g_amp).on(q))
                if g_phi > 0:
                    noisy.append(cirq.phase_damp(g_phi).on(q))
        return noisy


