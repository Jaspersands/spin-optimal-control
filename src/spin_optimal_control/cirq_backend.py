def _unitary_superop(U: np.ndarray) -> np.ndarray:
    return np.kron(U.conj(), U)


def _depolarizing_superop(p: float, n_qubits: int) -> np.ndarray:
    """ρ ↦ (1 − p)ρ + p/(4ⁿ−1) Σ_{P≠I} PρP  (cirq.depolarize convention)."""
    from functools import reduce
    paulis1 = [np.eye(2), np.array([[0, 1], [1, 0]]), np.array([[0, -1j], [1j, 0]]), np.diag([1.0, -1.0])]
    import itertools
    d = 2**n_qubits
    S = (1.0 - p) * np.eye(d * d, dtype=np.complex128)
    for combo in itertools.product(range(4), repeat=n_qubits):
        if all(c == 0 for c in combo):
            continue
        P = reduce(np.kron, [paulis1[c] for c in combo]).astype(np.complex128)
        S = S + (p / (4**n_qubits - 1)) * _unitary_superop(P)
    return S


def best_z_corrected_cz(U: np.ndarray) -> np.ndarray:
    """Apply the virtual-Z corrections that make a controlled-phase-like U closest to CZ."""
    d = np.diag(U)
    a = np.angle(d[0])
    z = np.diag([1.0, np.exp(-1j * (np.angle(d[1]) - a)), np.exp(-1j * (np.angle(d[2]) - a)),
                 np.exp(-1j * (np.angle(d[1]) + np.angle(d[2]) - 2 * a))]) * np.exp(-1j * a)
    return z @ np.asarray(U, dtype=np.complex128)


class CompiledCliffordRB:
    """
    Two-qubit Clifford RB on native spin-qubit gates.

    Parameters
    ----------
    noise_model : T1 / T2* (and temperature) of both electrons
    t_pulse_ns : duration of one ±π/2 EDSR pulse (layers run both qubits in parallel)
    t_cz_ns : duration of the CZ
    p_pulse : extra single-qubit depolarising probability per π/2 pulse
    p_cz : extra two-qubit depolarising probability per CZ
    cz_unitary : the implemented CZ (default ideal); pass e.g. a shaped-pulse
        propagator after ``best_z_corrected_cz`` to include coherent leakage.
    """

    def __init__(
        self,
        noise_model: Optional[SiliconNoiseModel] = None,
        t_pulse_ns: float = 50.0,
        t_cz_ns: float = 100.0,
        p_pulse: float = 0.0,
        p_cz: float = 0.0,
        cz_unitary: Optional[np.ndarray] = None,
    ):
        from .clifford_compiler import one_qubit_cliffords, two_qubit_cliffords

        self.noise = noise_model or SiliconNoiseModel(t1_us=1e9, t2_star_us=1e9, charge_noise_amp=0.0, overhauser_sigma=0.0)
        self.t_pulse, self.t_cz = float(t_pulse_ns), float(t_cz_ns)
        self.p_pulse, self.p_cz = float(p_pulse), float(p_cz)
        self.c1 = one_qubit_cliffords()
        self.c2 = two_qubit_cliffords()
        cz = np.diag([1, 1, 1, -1]).astype(np.complex128) if cz_unitary is None else np.asarray(cz_unitary, dtype=np.complex128)
        self._idle_cache: Dict[int, np.ndarray] = {}
        dep_cz = _depolarizing_superop(self.p_cz, 2) if self.p_cz > 0 else np.eye(16)
        self.cz_superop = self._idle(self.t_cz) @ dep_cz @ _unitary_superop(cz)
        self._local_cache: Dict[Tuple[int, int], np.ndarray] = {}
        self._clifford_cache: Dict[int, np.ndarray] = {}
        dep1 = _depolarizing_superop(self.p_pulse, 1) if self.p_pulse > 0 else np.eye(4)
        self._dep_pulse = [np.linalg.matrix_power(dep1, k) for k in range(4)]

    # ----------------------------------------------------------------- #
    def _idle(self, duration_ns: float) -> np.ndarray:
        key = int(round(duration_ns * 1000))
        if key not in self._idle_cache:
            self._idle_cache[key] = self.noise.idle_superoperator(duration_ns)
        return self._idle_cache[key]

    def _local_superop(self, a: int, b: int) -> np.ndarray:
        if (a, b) not in self._local_cache:
            ca, cb = self.c1[a], self.c1[b]
            U = np.kron(ca.unitary, cb.unitary)
            # per-qubit pulse errors: (D_a ⊗ D_b) in column-stacking order is a reshuffle; build via Kraus-free product
            dep = _two_local(self._dep_pulse[ca.n_pulses], self._dep_pulse[cb.n_pulses])
            duration = max(ca.n_pulses, cb.n_pulses) * self.t_pulse
            self._local_cache[(a, b)] = self._idle(duration) @ dep @ _unitary_superop(U)
        return self._local_cache[(a, b)]

    def clifford_superop(self, index: int) -> np.ndarray:
        if index not in self._clifford_cache:
            S = np.eye(16, dtype=np.complex128)
            for kind, arg in self.c2[index].native_sequence():
                S = (self.cz_superop if kind == "cz" else self._local_superop(*arg)) @ S
            self._clifford_cache[index] = S
        return self._clifford_cache[index]

    def circuit(self, index: int, qubits: Optional[Sequence["cirq.Qid"]] = None) -> "cirq.Circuit":
        """The compiled native-gate circuit of Clifford ``index`` (for inspection / export)."""
        if not HAS_CIRQ:
            raise RuntimeError("Cirq is not installed.")
        q = list(qubits) if qubits is not None else cirq.LineQubit.range(2)
        gate = {"X/2": cirq.rx(np.pi / 2), "-X/2": cirq.rx(-np.pi / 2), "Y/2": cirq.ry(np.pi / 2),
                "-Y/2": cirq.ry(-np.pi / 2), "S": cirq.S}
        c = cirq.Circuit()
        for kind, arg in self.c2[index].native_sequence():
            if kind == "cz":
                c.append(cirq.CZ(q[0], q[1]), strategy=cirq.InsertStrategy.NEW_THEN_INLINE)
            else:
                ops = [gate[g](q[0]) for g in self.c1[arg[0]].gates] + [gate[g](q[1]) for g in self.c1[arg[1]].gates]
                c.append(ops)
        return c

    # ----------------------------------------------------------------- #
    def _survival(self, lengths, n_sequences, rng, interleave_cz: bool) -> Tuple[List[float], List[float]]:
        from .clifford_compiler import lookup_two_qubit_clifford

        cz_ideal = np.diag([1, 1, 1, -1]).astype(np.complex128)
        rho0 = np.zeros(16, dtype=np.complex128); rho0[0] = 1.0     # vec(|00⟩⟨00|)
        means, stds = [], []
        for m in lengths:
            vals = []
            for _ in range(int(n_sequences)):
                vec = rho0.copy()
                acc = np.eye(4, dtype=np.complex128)
                for _ in range(int(m)):
                    k = int(rng.integers(len(self.c2)))
                    vec = self.clifford_superop(k) @ vec
                    acc = self.c2[k].unitary @ acc
                    if interleave_cz:
                        vec = self.cz_superop @ vec
                        acc = cz_ideal @ acc
                inv = lookup_two_qubit_clifford(acc.conj().T)
                vec = self.clifford_superop(inv) @ vec
                vals.append(float(np.real(vec[0])))
            means.append(float(np.mean(vals)))
            stds.append(float(np.std(vals)))
        return means, stds

    def run(self, lengths: Sequence[int], n_sequences: int = 20, seed: Optional[int] = None) -> Dict[str, Any]:
        """Reference RB: survival of |00⟩, fit, error per Clifford, native gate counts."""
        rng = np.random.default_rng(seed)
        means, stds = self._survival(lengths, n_sequences, rng, interleave_cz=False)
        A, p, B = rb_fit(lengths, means)
        return {"lengths": list(lengths), "fidelities": means, "std_errors": stds, "decay_p": p, "fit_A": A, "fit_B": B,
                "clifford_error": clifford_error_from_p(p), **self.gate_statistics()}

    def run_interleaved_cz(self, lengths: Sequence[int], n_sequences: int = 20, seed: Optional[int] = None) -> Dict[str, Any]:
        """Interleaved RB of the native CZ: r_CZ = (1 − 1/d)(1 − p_int/p_ref)."""
        rng = np.random.default_rng(seed)
        ref, _ = self._survival(lengths, n_sequences, rng, interleave_cz=False)
        inter, _ = self._survival(lengths, n_sequences, rng, interleave_cz=True)
        _, p_ref, _ = rb_fit(lengths, ref)
        _, p_int, _ = rb_fit(lengths, inter)
        err = max(0.0, 0.75 * (1.0 - p_int / p_ref)) if p_ref > 0 else float("nan")
        return {"lengths": list(lengths), "ref_fidelities": ref, "interleaved_fidelities": inter,
                "decay_p_ref": p_ref, "decay_p_interleaved": p_int, "cz_error": err}

    def gate_statistics(self) -> Dict[str, float]:
        n_cz = np.array([c.n_cz for c in self.c2])
        pulses = np.array([sum(max(self.c1[a].n_pulses, self.c1[b].n_pulses) for a, b in c.layers) for c in self.c2])
        durations = n_cz * self.t_cz + pulses * self.t_pulse
        return {"mean_cz_per_clifford": float(n_cz.mean()), "mean_pulse_layers_per_clifford": float(pulses.mean()),
                "mean_clifford_duration_ns": float(durations.mean())}


def _two_local(S_a: np.ndarray, S_b: np.ndarray) -> np.ndarray:
    """Column-stacking superoperator of E_a ⊗ E_b from single-qubit superoperators."""
    # vec(ρ) index for ρ[(i1 i2), (j1 j2)] in column stacking is (j1 j2) * 4 + (i1 i2).
    # E_a ⊗ E_b acts as S[(j1' i1'), (j1 i1)] ⊗ S[(j2' i2'), (j2 i2)]; reorder indices accordingly.
    T = np.einsum("abcd,efgh->aebfcgdh", S_a.reshape(2, 2, 2, 2), S_b.reshape(2, 2, 2, 2))
    return T.reshape(16, 16)
